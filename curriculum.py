def total_lessons() -> int:
    return len(LESSON_ORDER)


def lesson_id_for_scheduler_index(idx: int) -> str:
    """Индекс урока из scheduler_course → lesson_id каталога."""
    if not LESSON_ORDER:
        return "M1-L1"
    return LESSON_ORDER[idx % len(LESSON_ORDER)]
