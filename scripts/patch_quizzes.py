def patch_curriculum():
    text = CURRICULUM.read_text(encoding="utf-8")

    total_patched = 0

    for lesson_id, new_quiz in NEW_QUIZZES.items():
        # Find the quiz block for this specific lesson.
        # Pattern: look for the lesson_id key, then find the "quiz": [...] block after it.
        # We search within a ~200-line window after the lesson key.

        # Match lesson as a dict key: "M1-L1": {
        lesson_marker = f'"{lesson_id}": {{'
        marker_pos = text.find(lesson_marker)
        if marker_pos == -1:
            print(f"  SKIP {lesson_id} — not found in file as dict key")
            continue

        # Find "quiz": [ after the lesson marker
        quiz_start = text.find('"quiz": [', marker_pos)
        if quiz_start == -1:
            print(f"  SKIP {lesson_id} — no quiz block found")
            continue

        # Make sure quiz belongs to this lesson: no other lesson key between marker and quiz
        next_lesson_pos = len(text)
        for other_id in NEW_QUIZZES:
            if other_id == lesson_id:
                continue
            pos = text.find(f'"{other_id}": {{', marker_pos + 1)
            if pos != -1 and pos < next_lesson_pos:
                next_lesson_pos = pos

        if quiz_start > next_lesson_pos:
            print(f"  SKIP {lesson_id} — quiz block belongs to next lesson")
            continue

        # Find the closing ] of the quiz list
        # Count brackets from the [ after '"quiz": '
        bracket_start = quiz_start + len('"quiz": ')
        assert text[bracket_start] == '[', f"Expected '[' at {bracket_start}"

        depth = 0
        i = bracket_start
        while i < len(text):
            if text[i] == '[':
                depth += 1
            elif text[i] == ']':
                depth -= 1
                if depth == 0:
                    break
            i += 1

        quiz_end = i + 1  # after the closing ]

        # Build new quiz text
        lines = ['        "quiz": [']
        for q in new_quiz:
            lines.append('            {')
            lines.append(f'                "q": {repr(q["q"])},')
            lines.append('                "options": [')
            for opt in q['options']:
                lines.append(f'                    {repr(opt)},')
            lines.append('                ],')
            lines.append(f'                "correct": {q["correct"]},')
            lines.append(f'                "wrong_hint": {repr(q["wrong_hint"])},')
            lines.append('            },')
        lines.append('        ]')

        new_quiz_text = '\n'.join(lines)

        # Replace old quiz block with new one
        old_quiz_text = text[quiz_start:quiz_end]
        text = text[:quiz_start] + new_quiz_text + text[quiz_end:]

        print(f"  OK  {lesson_id} — {len(new_quiz)} questions patched")
        total_patched += 1

    CURRICULUM.write_text(text, encoding="utf-8")
    print(f"\nDone. Patched {total_patched}/{len(NEW_QUIZZES)} lessons.")


if __name__ == "__main__":
    print("Patching quiz questions in curriculum.py...")
    patch_curriculum()
